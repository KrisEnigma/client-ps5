//! Embeds the third-party notices the About screen shows. On the PS5 target the notices are
//! regenerated from `cargo metadata` first; elsewhere whatever file exists is embedded.
fn main() {
    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR set by cargo");
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR set by cargo");
    let root = format!("{manifest_dir}/../..");
    println!("cargo:rerun-if-changed={root}/Cargo.lock");
    println!("cargo:rerun-if-changed={root}/THIRD-PARTY-NOTICES.txt");
    if std::env::var("CARGO_CFG_TARGET_VENDOR").as_deref() == Ok("sie") {
        generate_third_party_notices(&root);
    }
    let text = std::fs::read(format!("{root}/THIRD-PARTY-NOTICES.txt"))
        .unwrap_or_else(|_| b"Notices are generated by the PS5 build (task build).".to_vec());
    let packed = miniz_oxide::deflate::compress_to_vec(&text, 9);
    std::fs::write(format!("{out_dir}/notices.deflate"), packed).expect("write notices.deflate");
}

fn generate_third_party_notices(root: &str) {
    use std::collections::HashMap;
    use std::fs;
    use std::path::Path;
    use std::process::Command;

    const BUNDLED_COMPONENTS: &[(&str, &str, Option<&str>, &str)] = &[
        ("ps5-payload-sdk startup code and libc shims",
         "Linked into test builds only. GPL-3.0-or-later; plan WP6 replaces it before any release.",
         None,
         "https://github.com/ps5-payload-dev/sdk"),
        ("Mesa RADV (PS5 port)",
         "The Vulkan driver, a static archive linked into the title. MIT License, with zlib and zstd (zlib/BSD).",
         None,
         "https://github.com/ps5-payload-dev/pacbrew-repo/tree/master/mesa"),
        ("PyroWave and Granite",
         "GPU wavelet decoder, linked through pyrowave-sys. MIT License.",
         None,
         "https://github.com/Themaister/pyrowave"),
        ("Skia",
         "2D graphics for the console UI, linked through skia-safe, with its bundled FreeType. BSD-3-Clause; FreeType License.",
         None,
         "https://skia.org"),
        ("libc++",
         "LLVM C++ runtime for RADV, PyroWave and Skia. Apache-2.0 WITH LLVM-exception.",
         None,
         "https://libcxx.llvm.org"),
        ("libopus",
         "Audio decode, linked through the opus crate. BSD-3-Clause.",
         None,
         "https://opus-codec.org"),
        ("Geist (Geist Sans)",
         "punktfunk's typeface, embedded by the console kit (pf-console-ui). SIL Open Font License 1.1.",
         Some("assets/licenses/Geist-OFL.txt"),
         "https://github.com/vercel/geist-font"),
        ("Lucide icons",
         "Icon path data embedded by the console kit (pf-console-ui). ISC License.",
         Some("assets/licenses/LICENSE-lucide.txt"),
         "https://lucide.dev"),
    ];

    // Run cargo metadata to get the dependency graph filtered for the webOS target
    let metadata_output = Command::new("cargo")
        .args(["metadata", "--locked", "--format-version", "1"])
        .current_dir(root)
        .output()
        .expect("run cargo metadata");

    if !metadata_output.status.success() {
        eprintln!(
            "cargo metadata failed: {}",
            String::from_utf8_lossy(&metadata_output.stderr)
        );
        std::process::exit(1);
    }

    let metadata: serde_json::Value =
        serde_json::from_slice(&metadata_output.stdout).expect("parse cargo metadata JSON");

    let ws_members: std::collections::HashSet<_> = metadata["workspace_members"]
        .as_array()
        .map(|arr| arr.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();

    let mut pkgs: Vec<_> = metadata["packages"]
        .as_array()
        .unwrap_or(&vec![])
        .iter()
        .filter_map(|pkg| {
            let id = pkg["id"].as_str()?;
            if ws_members.contains(id) {
                None
            } else {
                Some(pkg.clone())
            }
        })
        .collect();

    // Sort by name and version
    pkgs.sort_by(|a, b| {
        let a_name = a["name"].as_str().unwrap_or("").to_lowercase();
        let b_name = b["name"].as_str().unwrap_or("").to_lowercase();
        match a_name.cmp(&b_name) {
            std::cmp::Ordering::Equal => {
                let a_ver = a["version"].as_str().unwrap_or("");
                let b_ver = b["version"].as_str().unwrap_or("");
                a_ver.cmp(b_ver)
            }
            other => other,
        }
    });

    // Group license texts: text -> (filename, crates)
    let mut texts: HashMap<String, (String, std::collections::BTreeSet<String>)> = HashMap::new();
    let mut no_text = Vec::new();

    for pkg in &pkgs {
        let pkg_dir = Path::new(pkg["manifest_path"].as_str().unwrap_or(""))
            .parent()
            .unwrap_or_else(|| Path::new(""));
        let files = find_license_files(pkg_dir);
        let label = format!(
            "{} {}",
            pkg["name"].as_str().unwrap_or(""),
            pkg["version"].as_str().unwrap_or("")
        );

        if files.is_empty() {
            no_text.push(pkg.clone());
            continue;
        }

        for (fname, txt) in files {
            texts
                .entry(txt)
                .or_insert_with(|| (fname, std::collections::BTreeSet::new()))
                .1
                .insert(label.clone());
        }
    }

    // Process bundled components
    let mut bundled = Vec::new();
    for (label, blurb, lic_path, url) in BUNDLED_COMPONENTS {
        bundled.push((*label, *blurb, *url));
        if let Some(path) = lic_path {
            let full_path = Path::new(root).join(path);
            if let Ok(txt) = fs::read_to_string(&full_path) {
                let txt = txt.trim().to_string();
                if !txt.is_empty() {
                    let fname = Path::new(path)
                        .file_name()
                        .unwrap_or_default()
                        .to_string_lossy()
                        .to_string();
                    texts
                        .entry(txt)
                        .or_insert_with(|| (fname, std::collections::BTreeSet::new()))
                        .1
                        .insert(label.to_string());
                }
            }
        }
    }

    // Build the output document
    let mut lines = Vec::new();
    lines.push("THIRD-PARTY SOFTWARE NOTICES".to_string());
    lines.push("=".repeat(76));
    lines.push(String::new());
    lines.push("punktfunk-ps5 (https://github.com/punktfunk/client-ps5) source is licensed under".to_string());
    lines.push("MIT OR Apache-2.0, matching upstream punktfunk (https://git.unom.io/unom/punktfunk).".to_string());
    lines.push("Released binaries are MIT OR Apache-2.0 too. Unreleased test builds link".to_string());
    lines.push("GPL-3.0-or-later startup code and are GPL-3.0-or-later.".to_string());
    lines.push("It links the Rust crates listed below and the non-Rust components listed first;".to_string());
    lines.push("the full license texts follow the manifest.".to_string());
    lines.push(String::new());
    lines.push("Generated by build.rs — do not edit by hand.".to_string());
    lines.push(String::new());
    lines.push(format!("Total third-party crates: {}", pkgs.len()));
    lines.push(String::new());

    if !bundled.is_empty() {
        lines.push("-".repeat(76));
        lines.push("BUNDLED / EMBEDDED NON-RUST COMPONENTS".to_string());
        lines.push("-".repeat(76));
        for (label, blurb, url) in &bundled {
            lines.push(format!("  {}", label));
            lines.push(format!("      {}", blurb));
            lines.push(format!("      {}", url));
        }
        lines.push(String::new());
    }

    lines.push("-".repeat(76));
    lines.push("MANIFEST (crate version — SPDX license — source)".to_string());
    lines.push("-".repeat(76));
    for pkg in &pkgs {
        let name = pkg["name"].as_str().unwrap_or("");
        let version = pkg["version"].as_str().unwrap_or("");
        let license = if let Some(lic) = pkg["license"].as_str() {
            lic.to_string()
        } else if let Some(lic_file) = pkg["license_file"].as_str() {
            format!("file: {}", lic_file)
        } else {
            "UNKNOWN".to_string()
        };
        let repo = pkg["repository"].as_str().unwrap_or("");
        if repo.is_empty() {
            lines.push(format!("  {} {} — {}", name, version, license));
        } else {
            lines.push(format!("  {} {} — {} — {}", name, version, license, repo));
        }
    }
    lines.push(String::new());

    if !no_text.is_empty() {
        lines.push("-".repeat(76));
        lines.push("Crates whose package did not embed a license file (SPDX + source only)".to_string());
        lines.push("-".repeat(76));
        for pkg in &no_text {
            let name = pkg["name"].as_str().unwrap_or("");
            let version = pkg["version"].as_str().unwrap_or("");
            let license = pkg["license"].as_str().unwrap_or("UNKNOWN");
            let repo = pkg["repository"].as_str().unwrap_or("");
            if repo.is_empty() {
                lines.push(format!("  {} {} — {}", name, version, license));
            } else {
                lines.push(format!("  {} {} — {} — {}", name, version, license, repo));
            }
        }
        lines.push(String::new());
    }

    lines.push("=".repeat(76));
    lines.push("FULL LICENSE TEXTS (deduplicated)".to_string());
    lines.push("=".repeat(76));

    // Sort texts by the first (lowest) crate name in each group, then by text content for determinism
    let mut texts_vec: Vec<_> = texts.into_iter().collect();
    texts_vec.sort_by(|a, b| {
        let a_first = a.1 .1.iter().next().unwrap_or(&String::new()).to_lowercase();
        let b_first = b.1 .1.iter().next().unwrap_or(&String::new()).to_lowercase();
        match a_first.cmp(&b_first) {
            std::cmp::Ordering::Equal => a.0.cmp(&b.0),
            other => other,
        }
    });

    for (txt, (fname, crates)) in &texts_vec {
        lines.push(String::new());
        lines.push("-".repeat(76));
        let crates_str = crates.iter().map(String::as_str).collect::<Vec<_>>().join(", ");
        lines.push(format!("The following license ({}) applies to: {}", fname, crates_str));
        lines.push("-".repeat(76));
        lines.push(txt.clone());
        lines.push(String::new());
    }

    let output = lines.join("\n") + "\n";
    let output_path = Path::new(root).join("THIRD-PARTY-NOTICES.txt");
    fs::write(&output_path, output).expect("write THIRD-PARTY-NOTICES.txt");
    eprintln!(
        "wrote THIRD-PARTY-NOTICES.txt: {} crates, {} distinct license texts, {} without embedded text",
        pkgs.len(),
        texts_vec.len(),
        no_text.len()
    );
}

fn find_license_files(pkg_dir: &std::path::Path) -> Vec<(String, String)> {
    const LICENSE_GLOBS: &[&str] = &["license", "licence", "copying", "notice", "unlicense", "copyright"];
    let mut out = Vec::new();

    if let Ok(entries) = std::fs::read_dir(pkg_dir) {
        let mut names: Vec<_> = entries.filter_map(|e| e.ok().map(|entry| entry.path())).collect();
        names.sort();

        for path in names {
            if let Some(name) = path.file_name() {
                let name_str = name.to_string_lossy();
                let name_lower = name_str.to_lowercase();
                let is_license = LICENSE_GLOBS.iter().any(|glob| name_lower.contains(glob));

                if is_license && path.is_file() {
                    if let Ok(txt) = std::fs::read_to_string(&path) {
                        let txt = txt.trim().to_string();
                        if !txt.is_empty() {
                            out.push((name_str.to_string(), txt));
                        }
                    }
                }
            }
        }
    }

    out
}
